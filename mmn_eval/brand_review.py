"""Isolated v4 replay evaluator; does not change the shared Eval rubric.

An approval pin must be obtained separately from the product owner's frozen
registry. A digest binds that trusted registry; it does not prove who authored
an arbitrary file. Neither datasets, providers nor public APIs may supply the
trusted pin. No registry or Gold labels are generated by this module.
"""
import hashlib
import json
from collections import Counter

from brand_review_policy import RULE_VERSION, fuse_layered_reviews, validate_layered_reviews

CLASSES = ('publish', 'source_only', 'dispute', 'block')
PUBLISHED = {'source_only', 'supported', 'candidate'}
RUBRIC = {'version': 'brand-review-eval-rubric-v1', 'minRecoveryRate': .8,
          'minHoldoutRecoveryRate': .8, 'maxUnsafePublications': 0,
          'minHardBlockRate': 1, 'minCitationCompleteness': 1,
          'falseBlockPolicy': 'report_and_recovery_gate'}


def _digest(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                    separators=(',', ':'), allow_nan=False).encode()).hexdigest()


def _approval_failures(cases, approval, pin):
    if not isinstance(approval, dict) or not pin:
        return ['human_approval_missing']
    if _digest(approval) != pin:
        return ['approval_integrity_failed']
    failures = []
    if approval.get('datasetHash') != _digest(cases):
        failures.append('approval_dataset_mismatch')
    if (approval.get('ruleVersion') != RULE_VERSION or not approval.get('approvedBy')
            or not approval.get('approvedAt') or approval.get('thresholdsApproved') is not True
            or approval.get('rubric') != RUBRIC):
        failures.append('approval_contract_incomplete')
    entries = approval.get('cases')
    if not isinstance(entries, list) or len(entries) != len(cases):
        return failures + ['approval_cases_incomplete']
    registry = {entry.get('caseId'): entry for entry in entries if isinstance(entry, dict)}
    if len(registry) != len(entries):
        failures.append('approval_cases_incomplete')
    records, declarations = {}, set()
    for case in cases:
        if not isinstance(case, dict):
            failures.append('approval_case_mismatch')
            continue
        entry = registry.get(case.get('caseId'), {})
        if (entry.get('caseHash') != _digest(case) or entry.get('sourceKind') != case.get('sourceKind')
                or entry.get('evidenceGroupId') != case.get('evidenceGroupId')
                or entry.get('declarationId') != case.get('declarationId')
                or not isinstance(entry.get('sourceRecordId'), str) or not entry['sourceRecordId'].strip()):
            failures.append('approval_case_mismatch')
        record, group, declaration = entry.get('sourceRecordId'), entry.get('evidenceGroupId'), entry.get('declarationId')
        if not all(isinstance(v, str) and v.strip() for v in (record, group, declaration)):
            failures.append('approval_group_contract_incomplete')
            continue
        if record in records and records[record] != group:
            failures.append('source_record_group_mismatch')
        records[record] = group
        if (record, declaration) in declarations:
            failures.append('duplicate_approved_declaration')
        declarations.add((record, declaration))
    return failures


def _replay(case):
    packet, reviews = case['packet'], case['reviews']
    records = validate_layered_reviews(reviews, packet, actor_id='offline:brand-review-eval',
                                       server_time='2026-09-08T00:00:00Z')
    decision = fuse_layered_reviews(reviews, packet, records)
    keys = {r['semanticKey'] for r in records if r['claimId'] == case['targetClaimId']}
    if len(keys) != 1:
        raise ValueError('target_claim_missing_or_ambiguous')
    target_key = next(iter(keys))
    rows = decision['brandConclusions'] + decision['pairwiseConclusions']
    claims = {c['claimId']: c for row in rows for layer in ('facts', 'insights', 'actionOptions', 'unknowns')
              for c in row[layer]}
    target = claims[target_key]
    target_row = next(row for row in rows if any(c['claimId'] == target_key
                      for layer in ('insights', 'actionOptions', 'unknowns') for c in row[layer]))
    state = target['publicationStatus']
    actual = ('publish' if state in {'supported', 'candidate'} else 'block' if state == 'blocked'
              else 'dispute' if state == 'disputed' else 'source_only' if target_row['facts'] else 'unknown')
    published = [c for c in claims.values() if c['publicationStatus'] in PUBLISHED]
    sources = {row['id']: row for row in packet['evidence']}

    def anchored(c):
        refs = c.get('evidenceRefs')
        if not refs:
            return False
        for ref in refs:
            source = sources.get(ref.get('evidenceId'))
            if not source or ref.get('sourceFingerprint') != source['sourceFingerprint']:
                return False
            text = source['text'] or source['title']
            start, end = ref.get('span', [None, None])
            if (not isinstance(start, int) or not isinstance(end, int) or start < 0 or end <= start
                    or text[start:end] != ref.get('quote') or ref.get('brand') != source['brand']
                    or ref.get('publishedAt') != source['publishedAt']
                    or ref.get('sourceUrl') != source['sourceUrl']):
                return False
        return True

    expected = case['gold']['expectedClass']
    return {'caseId': case['caseId'], 'split': case['split'], 'sourceKind': case['sourceKind'],
            'expectedClass': case['gold']['expectedClass'], 'actualClass': actual,
            'hit': actual == expected,
            'falseBlock': expected == 'publish' and actual != 'publish',
            'falseAllow': actual == 'publish' and expected != 'publish',
            'classificationReason': 'matches_gold' if actual == expected else f'expected_{expected}_actual_{actual}',
            'publicationStatus': state, 'substantiveContentAvailable': actual in ('publish', 'source_only'),
            'publishedClaimCount': len(published), 'anchoredClaimCount': sum(anchored(c) for c in published)}


def evaluate_brand_reviews(cases, *, approval=None, trusted_approval_sha256=None):
    """Recompute candidate outputs, then compare to separately approved Gold.

    `passed` concerns only this offline replay, never deployment/enablement.
    Missing provenance, labels, denominators or holdout data means not_ready.
    """
    if not isinstance(cases, list) or len(cases) > 1000:
        raise ValueError('case_list_required_max_1000')
    dataset_hash = _digest(cases)
    approval_failures = _approval_failures(cases, approval, trusted_approval_sha256)
    blockers = list(approval_failures)
    if len(cases) < 60:
        blockers.append('minimum_60_cases_required')
    outcomes, source_counts, class_counts, splits = [], Counter(), Counter(), {}
    case_ids, declarations, group_splits = set(), set(), {}
    for case in cases:
        try:
            if not isinstance(case, dict) or not isinstance(case.get('caseId'), str):
                raise ValueError('invalid_case')
            if case['caseId'] in case_ids:
                blockers.append('duplicate_case_id')
            case_ids.add(case['caseId'])
            if case['sourceKind'] not in ('synthetic', 'historical_redacted'):
                raise ValueError('invalid_origin')
            if case['split'] not in ('development', 'holdout'):
                raise ValueError('invalid_split')
            if not all(isinstance(case.get(k), str) and 1 <= len(case[k].strip()) <= 256
                       for k in ('evidenceGroupId', 'declarationId')):
                raise ValueError('invalid_group_contract')
            group = case['evidenceGroupId']
            if group in group_splits and group_splits[group] != case['split']:
                blockers.append('evidence_group_split_leakage')
            group_splits[group] = case['split']
            declaration = (group, case['declarationId'])
            if declaration in declarations:
                blockers.append('duplicate_approved_declaration')
                continue
            declarations.add(declaration)
            if case['gold']['expectedClass'] not in CLASSES:
                raise ValueError('invalid_gold_class')
            if any(type(case['gold'].get(k)) is not bool for k in ('recoverable', 'v3Blocked')):
                raise ValueError('invalid_gold_flags')
            if not case['snapshotId'] or case['snapshotId'] != case['packet']['scope']['snapshotId']:
                raise ValueError('snapshot_mismatch')
            for key in ('snapshot:' + case['snapshotId'], 'evidence:' + _digest(case['packet']['evidence'])):
                if key in splits and splits[key] != case['split']:
                    blockers.append('snapshot_split_leakage')
                splits[key] = case['split']
            source_counts[case['sourceKind']] += 1
            class_counts[case['gold']['expectedClass']] += 1
            outcomes.append(_replay(case))
        except (ValueError, KeyError, TypeError, IndexError, AttributeError, OverflowError):
            blockers.append('invalid_case_or_policy_replay')
    if source_counts['historical_redacted'] < 30:
        blockers.append('minimum_30_historical_cases_required')
    if any(class_counts[c] < 10 for c in CLASSES):
        blockers.append('minimum_10_per_class_required')
    if set(splits.values()) != {'development', 'holdout'}:
        blockers.append('development_and_holdout_required')
    by_id = {c['caseId']: c for c in cases if isinstance(c, dict) and isinstance(c.get('caseId'), str)}
    eligible = [r for r in outcomes if by_id[r['caseId']]['gold']['recoverable']
                and by_id[r['caseId']]['gold']['v3Blocked']]
    recoveries = sum(r['substantiveContentAvailable'] for r in eligible)
    hard = [r for r in outcomes if r['expectedClass'] == 'block']
    blocked = sum(r['actualClass'] == 'block' for r in hard)
    unsafe = sum(r['actualClass'] == 'publish' and r['expectedClass'] != 'publish' for r in outcomes)
    claims = sum(r['publishedClaimCount'] for r in outcomes)
    anchored = sum(r['anchoredClaimCount'] for r in outcomes)
    if not eligible or not hard or not claims:
        blockers.append('zero_metric_denominator')
    trusted = not approval_failures
    metrics = {'recoveryNumerator': recoveries, 'recoveryDenominator': len(eligible),
               'recoveryRate': recoveries / len(eligible) if trusted and eligible else None,
               'hardBlockNumerator': blocked, 'hardBlockDenominator': len(hard),
               'hardBlockRate': blocked / len(hard) if trusted and hard else None,
               'unsafePublications': unsafe, 'publishedClaimCount': claims,
               'anchoredClaimCount': anchored,
               'citationCompleteness': anchored / claims if trusted and claims else None,
               'legacyRecoverableBlocks': len(eligible),
               'hitCount': sum(r['hit'] for r in outcomes),
               'falseBlockCount': sum(r['falseBlock'] for r in outcomes),
               'falseAllowCount': sum(r['falseAllow'] for r in outcomes),
               'unansweredCount': sum(r['actualClass'] == 'unknown' for r in outcomes),
               'manualQueueCount': sum(r['publicationStatus'] in ('manual_required', 'review_incomplete', 'disputed') for r in outcomes)}
    failed = (unsafe > 0 or blocked != len(hard) or anchored != claims
              or (eligible and recoveries / len(eligible) < RUBRIC['minRecoveryRate']))
    split_metrics = {}
    for split in ('development', 'holdout'):
        split_rows = [r for r in outcomes if r['split'] == split]
        split_eligible = [r for r in eligible if r['split'] == split]
        split_recovered = sum(r['substantiveContentAvailable'] for r in split_eligible)
        split_metrics[split] = {
            'caseCount': len(split_rows),
            'recoveryNumerator': split_recovered,
            'recoveryDenominator': len(split_eligible),
            'recoveryRate': split_recovered / len(split_eligible) if trusted and split_eligible else None,
            'classCounts': dict(Counter(r['expectedClass'] for r in split_rows)),
        }
        if split == 'holdout':
            if not split_eligible:
                blockers.append('zero_holdout_recovery_denominator')
            elif split_recovered / len(split_eligible) < RUBRIC['minHoldoutRecoveryRate']:
                failed = True
    return {'schemaVersion': 'brand-review-eval-v1', 'ruleVersion': RULE_VERSION,
            'datasetHash': dataset_hash, 'approvalHash': trusted_approval_sha256 if trusted else None,
            'status': 'not_ready' if blockers else 'failed' if failed else 'passed',
            'assessmentScope': 'offline_policy_replay_only', 'releaseAuthorized': False,
            'rubric': dict(RUBRIC),
            'blockers': sorted(set(blockers)), 'sourceCounts': dict(source_counts),
            'classCounts': dict(class_counts), 'metrics': metrics, 'splitMetrics': split_metrics, 'cases': outcomes,
            'modelUsage': {'mode': 'offline_replay', 'calls': 0, 'realCost': None, 'realLatency': None}}
